import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(scriptDir, "..");
const iconsDir = path.join(packageRoot, "src/icons");
const manifestPath = path.join(iconsDir, "manifest.yaml");
const catalogPath = path.join(iconsDir, "catalog.ts");

function parseManifest(content) {
  const icons = [];
  let inIcons = false;

  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    if (trimmed === "icons:") {
      inIcons = true;
      continue;
    }
    if (inIcons && trimmed.startsWith("- ")) {
      icons.push(trimmed.slice(2).trim());
    }
  }

  if (icons.length === 0) {
    throw new Error("manifest.yaml must declare at least one icon");
  }

  return icons;
}

const HTML_COMMENT_PATTERN = /<!--[\s\S]*?-->/g;
const SVG_INNER_PATTERN = /<svg[\s\S]*?>([\s\S]*?)<\/svg>/;

function extractSvgInner(svgContent) {
  const withoutComment = svgContent.replace(HTML_COMMENT_PATTERN, "").trim();
  const match = withoutComment.match(SVG_INNER_PATTERN);
  if (!match) {
    throw new Error("Invalid Lucide SVG file");
  }
  return match[1].replace(/\s+/g, " ").trim();
}

function readOverrideInner(iconName) {
  const overridePath = path.join(iconsDir, "overrides", `${iconName}.svg`);
  try {
    return extractSvgInner(readFileSync(overridePath, "utf8"));
  } catch {
    return null;
  }
}

function readLucideInner(iconName) {
  const packageJsonPath = require.resolve("lucide-static/package.json");
  const lucideRoot = path.dirname(packageJsonPath);
  const svgPath = path.join(lucideRoot, "icons", `${iconName}.svg`);
  const svgContent = readFileSync(svgPath, "utf8");
  return extractSvgInner(svgContent);
}

function readIconInner(iconName) {
  return readOverrideInner(iconName) ?? readLucideInner(iconName);
}

function generateCatalog(icons) {
  const entries = icons.map((iconName) => {
    const inner = readIconInner(iconName);
    return `  "${iconName}": ${JSON.stringify(inner)},`;
  });

  return `// Generated by scripts/generate-html-icons.mjs — do not edit manually.
// Re-run: pnpm --filter @airp/renderer-target-html icons:generate

export const ICON_NAMES = ${JSON.stringify(icons)} as const;

export type IconName = (typeof ICON_NAMES)[number];

export const ICON_CATALOG: Record<IconName, string> = {
${entries.join("\n")}
};
`;
}

const manifest = readFileSync(manifestPath, "utf8");
const icons = parseManifest(manifest);
writeFileSync(catalogPath, generateCatalog(icons), "utf8");
console.log(`Generated ${catalogPath} (${icons.length} icons)`);
